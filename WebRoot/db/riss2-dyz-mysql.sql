-- RISS2 multilingual schema additions for MySQL 8.
-- Execute after database-riss2-mysql.sql.
SET NAMES utf8mb4;
USE riss2_mlan;

ALTER TABLE RES_META_STORE ADD COLUMN IF NOT EXISTS RMST_LANGUAGE VARCHAR(32);
ALTER TABLE RES_TEXT_LIBRARY ADD COLUMN IF NOT EXISTS RTLI_LANGUAGE VARCHAR(32);
ALTER TABLE RES_TEXT_RESOURCE ADD COLUMN IF NOT EXISTS RTRE_LANGUAGE VARCHAR(32);
ALTER TABLE IDS_INFORMATION_TYPE ADD COLUMN IF NOT EXISTS IDST_LANGUAGE VARCHAR(32);
ALTER TABLE IDS_INFORMATION ADD COLUMN IF NOT EXISTS IDSI_LANGUAGE VARCHAR(32);
ALTER TABLE RES_DYNAMIC_TYPE ADD COLUMN IF NOT EXISTS RDTY_ZW_NAME VARCHAR(1024);
ALTER TABLE RES_DYNAMIC_TYPE ADD COLUMN IF NOT EXISTS RDTY_EN_NAME VARCHAR(512);

-- Old catalogue tables are no longer used by the multilingual application.
DROP TABLE IF EXISTS RES_SOURCE_CATALOGUE;
DROP TABLE IF EXISTS RES_SOURCE_PIC;

CREATE TABLE IF NOT EXISTS SYS_API_DATA (
    SADA_ID BIGINT NOT NULL,
    SADA_TYPE VARCHAR(128),
    SADA_NAME VARCHAR(256),
    SADA_REQ_URL VARCHAR(512),
    SADA_DEMO_URL VARCHAR(512),
    SADA_REQ_TYPE VARCHAR(64),
    SADA_REQ_PARAMS LONGTEXT,
    SADA_RESULT LONGTEXT,
    SADA_REMARK LONGTEXT,
    SADA_INDEX DECIMAL(9,0),
    SADA_LAST_UPDATE DATETIME,
    SADA_UPDATE_REMARK VARCHAR(512),
    CONSTRAINT PK_SYS_API_DATA PRIMARY KEY (SADA_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

