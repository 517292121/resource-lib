-- RISS2 MySQL 8 triggers. Execute after database-riss2-mysql.sql.
USE riss2_mlan;

DROP TRIGGER IF EXISTS UPDATE_STATUS_FOR_META_STORE;
DROP TRIGGER IF EXISTS UPDATE_STATUS_FOR_MISSION;
DROP TRIGGER IF EXISTS DELETE_FOR_RESOURCE;

DELIMITER $$
CREATE TRIGGER UPDATE_STATUS_FOR_META_STORE
AFTER UPDATE ON RES_META_STORE
FOR EACH ROW
BEGIN
    IF NOT (NEW.RMST_STATUS <=> OLD.RMST_STATUS) THEN
        UPDATE RES_SOURCE_DATA
           SET RSDA_RMST_STATUS = NEW.RMST_STATUS
         WHERE RSDA_RMST_ID = NEW.RMST_ID;
    END IF;
END$$

CREATE TRIGGER UPDATE_STATUS_FOR_MISSION
AFTER UPDATE ON RES_MISSION_INFO
FOR EACH ROW
BEGIN
    IF NOT (NEW.RMIN_STATUS <=> OLD.RMIN_STATUS) THEN
        UPDATE RES_SOURCE_DATA
           SET RSDA_RMIN_STATUS = NEW.RMIN_STATUS
         WHERE RSDA_RMIN_ID = NEW.RMIN_ID;
    END IF;
END$$

CREATE TRIGGER DELETE_FOR_RESOURCE
AFTER DELETE ON RES_SOURCE_DATA
FOR EACH ROW
BEGIN
    DELETE FROM SC_FAVORITES WHERE SCF_RES_SOURCE_ID = OLD.RSDA_ID;
    DELETE FROM RES_TAG_INFO WHERE RTIN_RSDA_ID = OLD.RSDA_ID;
    DELETE FROM RES_SOURCE_BROWSE_HISTOREY WHERE RSBH_RSDA_ID = OLD.RSDA_ID;
    DELETE FROM RES_SOURCE_DATA_CACHE WHERE RSDC_ID = OLD.RSDA_ID;
END$$
DELIMITER ;
