-- 文献文本批注。首次启动自动执行此幂等建表语句，也可由 DBA 提前执行。
-- START_OFFSET / END_OFFSET 为归一化章节文本的 UTF-16 偏移；END_OFFSET 不包含在范围内。
-- 不存储屏幕页码，以免调整字号、窗口后批注错位。
CREATE TABLE IF NOT EXISTS RES_TEXT_ANNOTATION (
    ANNOTATION_ID VARCHAR(36) NOT NULL PRIMARY KEY,
    RESOURCE_ID BIGINT NOT NULL,
    USER_ID BIGINT NOT NULL,
    CHAPTER_PATH VARCHAR(1024) NOT NULL,
    TEXT_HASH CHAR(64) NOT NULL,
    START_OFFSET INT NOT NULL,
    END_OFFSET INT NOT NULL,
    ANNOTATION_SCOPE VARCHAR(16) NOT NULL,
    QUOTED_TEXT MEDIUMTEXT NOT NULL,
    CONTENT TEXT NOT NULL,
    CREATED_AT DATETIME(3) NOT NULL,
    UPDATED_AT DATETIME(3) NOT NULL,
    VERSION INT NOT NULL DEFAULT 0,
    AUDIT_STATUS VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    AUDIT_REMARK VARCHAR(1000) NULL,
    AUDIT_BY BIGINT NULL,
    AUDIT_AT DATETIME(3) NULL,
    INDEX IDX_TEXT_ANNOTATION_RESOURCE (RESOURCE_ID),
    INDEX IDX_TEXT_ANNOTATION_USER (USER_ID, CREATED_AT),
    INDEX IDX_TEXT_ANNOTATION_AUDIT (AUDIT_STATUS, CREATED_AT)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
